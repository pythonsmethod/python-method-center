import os
import json
from anthropic import Anthropic

client = Anthropic(api_key=os.environ.get("ANTHROPIC_API_KEY"))

# История диалогов каждого пользователя
sessions = {}

# ================================================================
# LUCKY — Ангел-хранитель ресепшна
# ================================================================
LUCKY_PROMPT = """Ты — Lucky, ангел-хранитель реабилитационного центра Python Method.

Ты первая встречаешь каждого человека. 
К нам приходят люди с онкологией, тяжёлыми заболеваниями, 
и те кто хочет заботиться о своём здоровье.

Твоё первое сообщение всегда именно такое — слово в слово:
"Здравствуйте 🍀

Я — Lucky, ваш ангел-хранитель.

Это место создано для людей которым важно своё здоровье — и для тех кто ищет путь когда всё кажется сложным.

Расскажите — с чем вы пришли сегодня?

🔍 Хочу разобраться / есть вопросы
🛡 Хочу профилактику
💊 Есть диагноз или заболевание
📦 Хочу приобрести формулу"

Как ты говоришь:
- Просто и по-человечески
- Коротко — одна мысль, один вопрос
- Никогда не торопишь
- Никогда не говоришь "понимаю вашу боль" — это фальшь
- Говоришь "я здесь" и "мы разберёмся вместе"

Если человек пишет что ему страшно или он не знает что делать:
Не торопись к следующему шагу. Просто побудь рядом. 
Скажи что здесь безопасно. Что он пришёл в нужное место.

Когда человек выбрал направление — верни ТОЛЬКО JSON без лишнего текста:
{"route": "faq"} — если хочет разобраться или есть вопросы
{"route": "prevention"} — если хочет профилактику
{"route": "individual"} — если есть диагноз или заболевание
{"route": "formula"} — если хочет купить формулу

ВАЖНЫЕ ГРАНИЦЫ:
- Никогда не ставь диагнозов
- Никогда не давай медицинских назначений
- Никогда не обещай результат
- Ты ангел-хранитель — ты ведёшь, но не лечишь
"""

# ================================================================
# GABRIEL — Навигатор
# ================================================================
GABRIEL_PROMPT = """Ты — Gabriel, ангел-навигатор реабилитационного центра Python Method.

Ты помогаешь человеку найти свой путь внутри центра.
Ты спокойный, ясный, уверенный.

Когда понял куда человеку идти — верни ТОЛЬКО JSON:
{"route": "faq"} — вопросы и доверие
{"route": "prevention"} — профилактика
{"route": "individual"} — индивидуальное сопровождение
{"route": "formula"} — формула / продукт

Если непонятно — задай один уточняющий вопрос.
Пиши коротко и тепло.
"""

# ================================================================
# МАРШРУТИЗАТОР — какой агент отвечает
# ================================================================
AGENT_PROMPTS = {
    "reception": LUCKY_PROMPT,
    "navigation": GABRIEL_PROMPT,
}

AGENT_NAMES = {
    "reception": "Lucky 🍀",
    "navigation": "Gabriel ✨",
}


def get_session(contact_id: str) -> dict:
    if contact_id not in sessions:
        sessions[contact_id] = {
            "route": "reception",
            "history": [],
            "name": None,
        }
    return sessions[contact_id]


def process_message(contact_id: str, user_message: str) -> str:
    """
    Главная функция.
    Принимает сообщение от пользователя.
    Возвращает текст ответа.
    """
    session = get_session(contact_id)

    # Добавляем сообщение в историю
    session["history"].append({
        "role": "user",
        "content": user_message
    })

    # Берём промпт текущего агента
    current_route = session["route"]
    prompt = AGENT_PROMPTS.get(current_route, LUCKY_PROMPT)

    # Вызываем Claude
    response = client.messages.create(
        model="claude-sonnet-4-20250514",
        max_tokens=500,
        system=prompt,
        messages=session["history"][-10:]
    )

    reply = response.content[0].text.strip()

    # Сохраняем ответ в историю
    session["history"].append({
        "role": "assistant",
        "content": reply
    })

    # Проверяем — вернул ли агент маршрут
    try:
        data = json.loads(reply)
        if "route" in data:
            new_route = data["route"]
            session["route"] = new_route
            # Возвращаем переходное сообщение
            transitions = {
                "faq": "Провожу вас в кабинет вопросов и доверия ✨",
                "prevention": "Провожу вас в кабинет профилактики 🛡",
                "individual": "Провожу вас к индивидуальному сопровождению 💊",
                "formula": "Провожу вас в кабинет формулы 📦",
            }
            return transitions.get(new_route, "Провожу вас дальше...")
    except (json.JSONDecodeError, KeyError):
        pass

    return reply
