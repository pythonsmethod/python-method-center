def get_session(contact_id: str) -> dict:
    if contact_id not in sessions:
        sessions[contact_id] = {
            "route": "reception",
            "history": [],
        }
    return sessions[contact_id]


def extract_route(reply: str):
    """Достаём JSON {"route": "..."} из ответа агента."""
    s = reply.strip()
    # Чистый JSON
    try:
        data = json.loads(s)
        if isinstance(data, dict) and "route" in data:
            return data["route"]
    except (json.JSONDecodeError, ValueError):
        pass
    # JSON внутри текста
    m = re.search(r'\{\s*"route"\s*:\s*"([a-z_]+)"\s*\}', s)
    if m:
        return m.group(1)
    return None


def process_message(contact_id: str, user_message: str) -> str:
    """Главная функция: принимает сообщение, возвращает текст ответа."""
    session = get_session(contact_id)
    session["history"].append({"role": "user", "content": user_message})

    current_route = session["route"]
    prompt = AGENT_PROMPTS.get(current_route, LUCKY_PROMPT)

    try:
        response = client.messages.create(
            model=MODEL,
            max_tokens=600,
            system=prompt,
            messages=session["history"][-10:],
        )
        reply = response.content[0].text.strip()
    except Exception as e:
        print(f"[AI ERROR] {e}")
        return "Что-то на стороне системы. Напишите, пожалуйста, ещё раз через минуту 🌿"

    session["history"].append({"role": "assistant", "content": reply})

    # Проверяем — это команда перехода?
    new_route = extract_route(reply)
    if new_route and new_route in AGENT_PROMPTS:
        session["route"] = new_route
        session["history"] = []  # у нового агента свой контекст
        return TRANSITIONS.get(new_route, "Передаю вас дальше ✨")

    return reply
